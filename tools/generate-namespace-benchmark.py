#!/usr/bin/env python3
"""Generate exact-size namespace churn workloads and canonical summaries."""

from __future__ import annotations

import argparse
import csv
import filecmp
import json
import tempfile
from pathlib import Path


FNV_OFFSET = 14695981039346656037
FNV_PRIME = 1099511628211
DOCUMENT_OPEN = b"<root>"
DOCUMENT_CLOSE = b"</root>"
RECORDS = (
    (b'<p:n xmlns:p="urn:a" p:a="v"/>', b"urn:a"),
    (b'<p:n xmlns:p="urn:b" p:a="v"/>', b"urn:b"),
)
SCHEMA = "# z-xml-namespace-benchmark-v1"
DEFAULT_SIZES_KIB = "1,16,64,256,1024"


def fnv(value: int, data: bytes) -> int:
    for byte in data:
        value ^= byte
        value = (value * FNV_PRIME) & 0xFFFFFFFFFFFFFFFF
    return value


class Stats:
    def __init__(self) -> None:
        self.elements = 0
        self.attributes = 0
        self.text_bytes = 0
        self.name_bytes = 0
        self.value_bytes = 0
        self.namespace_declarations = 0
        self.namespace_uri_bytes = 0
        self.local_name_bytes = 0
        self.prefix_bytes = 0
        self.accumulator = FNV_OFFSET

    def bytes(self, value: bytes) -> None:
        self.accumulator = fnv(self.accumulator, value)

    def marker(self, value: int) -> None:
        self.bytes(bytes((value,)))

    def name(self, marker: int, uri: bytes, local: bytes, prefix: bytes) -> None:
        self.name_bytes += len(local) + (len(prefix) + 1 if prefix else 0)
        self.namespace_uri_bytes += len(uri)
        self.local_name_bytes += len(local)
        self.prefix_bytes += len(prefix)
        self.marker(marker)
        self.marker(7)
        self.bytes(uri)
        self.marker(8)
        self.bytes(local)
        self.marker(9)
        self.bytes(prefix)

    def declaration(self, prefix: bytes, uri: bytes) -> None:
        self.namespace_declarations += 1
        self.namespace_uri_bytes += len(uri)
        self.prefix_bytes += len(prefix)
        self.marker(5)
        self.bytes(prefix)
        self.marker(6)
        self.bytes(uri)

    def start(self, uri: bytes, local: bytes, prefix: bytes) -> None:
        self.elements += 1
        self.name(1, uri, local, prefix)

    def attribute(self, uri: bytes, local: bytes, prefix: bytes, value: bytes) -> None:
        self.attributes += 1
        self.value_bytes += len(value)
        self.name(2, uri, local, prefix)
        self.marker(3)
        self.bytes(value)

    def end(self, uri: bytes, local: bytes, prefix: bytes) -> None:
        self.name(4, uri, local, prefix)

    def summary(self) -> str:
        return json.dumps(
            {
                "elements": self.elements,
                "attributes": self.attributes,
                "text_bytes": self.text_bytes,
                "name_bytes": self.name_bytes,
                "value_bytes": self.value_bytes,
                "namespace_declarations": self.namespace_declarations,
                "namespace_uri_bytes": self.namespace_uri_bytes,
                "local_name_bytes": self.local_name_bytes,
                "prefix_bytes": self.prefix_bytes,
                "checksum": f"{self.accumulator:016x}",
            },
            separators=(",", ":"),
        )


def generate(path: Path, size: int) -> Stats:
    minimum_padding = len(b"<!---->")
    payload = size - len(DOCUMENT_OPEN) - len(DOCUMENT_CLOSE)
    if payload < len(RECORDS[0][0]) + minimum_padding:
        raise ValueError("target size is too small")
    record_count = (payload - minimum_padding) // len(RECORDS[0][0])
    padding = payload - record_count * len(RECORDS[0][0])
    stats = Stats()
    temporary = path.with_name(path.name + ".tmp")
    path.parent.mkdir(parents=True, exist_ok=True)
    with temporary.open("wb") as output:
        output.write(DOCUMENT_OPEN)
        stats.start(b"", b"root", b"")
        for index in range(record_count):
            record, uri = RECORDS[index % len(RECORDS)]
            output.write(record)
            stats.declaration(b"p", uri)
            stats.start(uri, b"n", b"p")
            stats.attribute(uri, b"a", b"p", b"v")
            stats.end(uri, b"n", b"p")
        output.write(b"<!--" + b"x" * (padding - minimum_padding) + b"-->")
        output.write(DOCUMENT_CLOSE)
        stats.end(b"", b"root", b"")
    temporary.replace(path)
    if path.stat().st_size != size:
        raise AssertionError("generated byte size differs")
    return stats


def write_manifest(output_dir: Path, rows: list[dict[str, object]]) -> Path:
    output_dir.mkdir(parents=True, exist_ok=True)
    manifest = output_dir / "manifest.tsv"
    with manifest.open("w", encoding="utf-8", newline="") as output:
        output.write(SCHEMA + "\n")
        writer = csv.DictWriter(output, rows[0].keys(), delimiter="\t", lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    return manifest


def generate_corpus(output_dir: Path, sizes: list[int]) -> Path:
    rows = []
    for size_kib in sizes:
        size = size_kib * 1024
        item_id = f"namespace-churn-{size_kib}k"
        relative = Path("valid") / f"{item_id}.xml"
        stats = generate(output_dir / relative, size)
        rows.append(
            {
                "id": item_id,
                "path": str(relative),
                "shape": "namespace-churn",
                "actual_bytes": size,
                "classification": "benchmark-valid",
                "expected_summary": stats.summary(),
            }
        )
    return write_manifest(output_dir, rows)


def files(root: Path) -> dict[str, Path]:
    return {
        str(path.relative_to(root)): path
        for path in root.rglob("*")
        if path.is_file()
    }


def check_corpus(output_dir: Path, sizes: list[int]) -> None:
    if not output_dir.is_dir():
        raise ValueError(f"missing namespace benchmark corpus: {output_dir}")
    with tempfile.TemporaryDirectory(prefix="z-xml-namespace-check-") as temporary:
        expected_dir = Path(temporary)
        generate_corpus(expected_dir, sizes)
        observed = files(output_dir)
        expected = files(expected_dir)
        if set(observed) != set(expected):
            missing = sorted(set(expected).difference(observed))
            extra = sorted(set(observed).difference(expected))
            details = []
            if missing:
                details.append(f"missing {', '.join(missing)}")
            if extra:
                details.append(f"unexpected {', '.join(extra)}")
            raise ValueError("namespace benchmark corpus file set differs: " + "; ".join(details))
        for relative in sorted(expected):
            if not filecmp.cmp(observed[relative], expected[relative], shallow=False):
                raise ValueError(f"namespace benchmark corpus differs: {relative}")


def parse_sizes(parser: argparse.ArgumentParser, value: str) -> list[int]:
    try:
        sizes = sorted({int(item) for item in value.split(",")})
    except ValueError:
        parser.error("sizes must be comma-separated integers")
    if not sizes or any(size <= 0 or size > 1024 * 1024 for size in sizes):
        parser.error("sizes must be positive KiB values at or below 1 GiB")
    return sizes


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--sizes-kib", default=DEFAULT_SIZES_KIB)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the corpus instead of rewriting it",
    )
    args = parser.parse_args()
    sizes = parse_sizes(parser, args.sizes_kib)
    if args.check:
        try:
            check_corpus(args.output_dir, sizes)
        except (OSError, ValueError) as error:
            print(error)
            return 1
        print(f"namespace benchmark corpus matches: {args.output_dir}")
        return 0

    manifest = generate_corpus(args.output_dir, sizes)
    print(f"namespace benchmark corpus: {len(sizes)} workloads")
    print(f"manifest: {manifest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
